// Joins the modules in src/ into gluebox.bundle.js: one ordinary (non-module) script that runs
// exactly the same code as src/main.js.
//
// Why: browsers refuse to load JavaScript modules from a page opened straight from disk
// (file://), so double-clicking index.html would show an empty menu. index.html runs this
// bundle in that case and the real modules whenever the page is served over http(s).
//
//   node tools/build.mjs           # rewrite gluebox.bundle.js after editing src/
//   node tools/build.mjs --check   # exit with an error if gluebox.bundle.js is out of date
//
// It understands only what src/ uses: `import { a, b } from './x.js'`,
// `import * as NAME from 'bare-name'` (resolved through the import map in index.html), and
// `export` in front of function / class / const / let declarations.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLE_PATH = resolve(ROOT, 'gluebox.bundle.js');
const ENTRY = resolve(ROOT, 'src/main.js');

const NAMED_IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'([^']+)';[ \t]*$/gm;
const NAMESPACE_IMPORT = /^import\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s*'([^']+)';[ \t]*$/gm;
const EXPORTED_DECLARATION = /^export\s+((?:async\s+)?(?:function\*?|class|const|let)\s+([A-Za-z_$][\w$]*))/gm;
const UNSUPPORTED = /^\s*(export\s+(default|\{|\*)|import\s*\(|import\s+[A-Za-z_$][\w$]*\s+from)|\bimport\.meta\b/m;

/** The URLs that bare module names map to, read from the import map in index.html. */
function importMap() {
  const html = readFileSync(resolve(ROOT, 'index.html'), 'utf8');
  const m = /<script type="importmap">([\s\S]*?)<\/script>/.exec(html);
  return m ? JSON.parse(m[1]).imports : {};
}

const moduleVar = (file) => '__' + relative(resolve(ROOT, 'src'), file).replace(/\.js$/, '').replace(/[^\w]/g, '_');
const externalVar = (name) => '__external_' + name.replace(/[^\w]/g, '_');

/** Build the bundle text. */
export function bundle() {
  const map = importMap();
  const externals = new Map(); // bare name -> URL
  const modules = new Map();   // file -> { prelude, body, exported } (null while being visited)
  const order = [];

  const visit = (file) => {
    if (modules.has(file)) {
      if (modules.get(file) === null) throw new Error(`import cycle through ${relative(ROOT, file)}`);
      return;
    }
    modules.set(file, null);
    let body = readFileSync(file, 'utf8');
    const prelude = [];
    body = body.replace(NAMESPACE_IMPORT, (_, name, spec) => {
      if (!map[spec]) throw new Error(`${relative(ROOT, file)}: "${spec}" is not in the import map`);
      externals.set(spec, map[spec]);
      prelude.push(`const ${name} = ${externalVar(spec)};`);
      return '';
    });
    body = body.replace(NAMED_IMPORT, (_, names, spec) => {
      const dep = resolve(dirname(file), spec);
      visit(dep);
      const list = names.split(',').map((s) => s.trim()).filter(Boolean);
      prelude.push(`const { ${list.join(', ')} } = ${moduleVar(dep)};`);
      return '';
    });
    if (UNSUPPORTED.test(body)) throw new Error(`${relative(ROOT, file)} uses import/export syntax build.mjs doesn't handle`);
    const exported = [];
    body = body.replace(EXPORTED_DECLARATION, (_, declaration, name) => { exported.push(name); return declaration; });
    modules.set(file, { prelude, body: body.trim(), exported });
    order.push(file);
  };
  visit(ENTRY);

  const parts = [
    '// Generated by tools/build.mjs from the modules in src/. Do not edit: change src/ and run',
    '// `npm run build`. index.html runs this file only when the page is opened from disk.',
    '(async () => {',
    "'use strict';",
    ...[...externals].map(([name, url]) => `const ${externalVar(name)} = await import(${JSON.stringify(url)});`),
  ];
  for (const file of order) {
    const { prelude, body, exported } = modules.get(file);
    parts.push(
      '',
      `// ---- src/${relative(resolve(ROOT, 'src'), file)}`,
      `const ${moduleVar(file)} = (() => {`,
      ...prelude,
      body,
      `return { ${exported.join(', ')} };`,
      '})();',
    );
  }
  parts.push(
    '})().catch((error) => {',
    "  window.dispatchEvent(new CustomEvent('gluebox:failed', { detail: error }));",
    '  throw error;',
    '});',
    '',
  );
  return parts.join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = bundle();
  if (process.argv.includes('--check')) {
    const current = readFileSync(BUNDLE_PATH, 'utf8');
    if (current !== text) {
      console.error('gluebox.bundle.js is out of date: run `npm run build`.');
      process.exit(1);
    }
    console.log('gluebox.bundle.js is up to date.');
  } else {
    writeFileSync(BUNDLE_PATH, text);
    console.log(`wrote ${relative(process.cwd(), BUNDLE_PATH)} (${text.length} bytes)`);
  }
}
